"""墙钟 —— 全项目**只有这一处**取时间。

为什么值得单独开一个 20 行的模块
───────────────────────────────────────────────────────────
Keel 里有两套「时间」，混用会直接毁掉证据：

    **故事内时点**  「第 3 章」           → 产品指标（哪几章的提案最常被采纳）
    **墙钟时刻**    2026-09-17T00:55:45+08:00 → 合规举证（人在哪个时刻做了判断）

举证用的时刻必须口径统一：带时区、精确到秒、同一序列化格式。
散在各处写 `datetime.now()` 的结果是有的带时区有的不带、有的到微秒有的到
秒 —— 等到要拿几条记录拼一条时间线时，它们对不齐，而**对不齐的时间线
在申诉现场等于没有时间线**。

── 为什么是**本地时区 + 偏移**，不是裸 UTC ──────────────────────
举证的人要拿这份记录去和别的材料对：文件的 mtime、聊天记录、平台后台的
投稿时间 —— 那些全是本地时间。记成裸 UTC 就得现场换算，而对不上时
（凌晨的稿子记成前一天）看起来像篡改。带 `+08:00` 的本地时刻既保留了
无歧义性，又能和作者手边的材料直接对上。

纪律（与 `provenance/telemetry.py` 的「不碰时钟」同源）
───────────────────────────────────────────────────────────
不是「不许有钟」，是**不许在纯函数里偷偷取钟**。所以：

  * 本模块的函数**接受** `ts` 参数 —— 测试可确定化，测不准的举证字段
    等于这条证据在测试里永远验不到。
  * 需要时刻的调用方（CLI / 自动驾驶 runner）显式调 `wall_iso()`，
    而不接收时刻注入的纯函数（IR / 校验器 / 渲染器）**一律不调它**。

    ⚠ 本模块是**自报时刻**，不是可信时间戳。
    Keel 不签名、不做第三方存证，这个时刻的法律效力取决于运行环境
    （改系统时间即可改它）。要更强的时间证据请用第三方时间戳服务 ——
    见 `provenance/process.py::GAPS`。把自报时刻说成可信时间戳，
    是把「我们记了」冒充成「有人作证」。
"""

from __future__ import annotations

import time
from datetime import datetime

__all__ = ["wall_iso"]


def wall_iso(ts: float | None = None) -> str:
    """取墙钟的 ISO 8601 字符串（秒精度，**本地时区 + UTC 偏移**）。

    `ts` 省略时才真的去读时钟；传值即纯函数 —— 这是本模块能被测试的原因。
    """
    when = datetime.fromtimestamp(ts if ts is not None else time.time()).astimezone()
    return when.isoformat(timespec="seconds")
